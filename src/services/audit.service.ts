export interface AuditEventInput {
	action: AuditActionCode | (string & {});
	entityType: AuditEntityType | (string & {});
	/** a numeric entity id is stored as String(id) (numeric-ID migration); string keys (reports) as-is */
	entityId?: number | string | null;
	companyId?: number | null;
	employeeId?: number | null;
	/** defaults to the authenticated user of the current request */
	actorUserId?: number | null;
	/** already-normalised diff (see buildChanges) — sanitised again here */
	changes?: Record<string, unknown> | null;
	/** small set of SAFE identifiers — never request bodies, reasons or secrets */
	metadata?: Record<string, unknown> | null;
	/** override the ambient request context (tests / background jobs) */
	requestContext?: Partial<RequestContext>;
}

export async function writeAuditEvent(db: AuditDb, input: AuditEventInput) {
	const ambient = getRequestContext();
	const ctx = { ...ambient, ...input.requestContext };
	const changes = input.changes ? sanitizeForAudit(input.changes) : null;
	const metadata = input.metadata ? sanitizeForAudit(input.metadata) : null;
	return db.auditEvent.create({
		data: {
			action: input.action,
			entityType: input.entityType,
			entityId:
				input.entityId === undefined || input.entityId === null ? null : String(input.entityId),
			companyId: input.companyId ?? null,
			employeeId: input.employeeId ?? null,
			actorUserId: input.actorUserId !== undefined ? input.actorUserId : (ctx.actorUserId ?? null),
			requestId: ctx.requestId ?? null,
			ipAddress: ctx.ipAddress ?? null,
			userAgent: ctx.userAgent ?? null,
			changesJson: changes === null ? Prisma.DbNull : changes,
			metadataJson: metadata === null ? Prisma.DbNull : metadata
		},
		select: { id: true }
	});
}

/** Picks the harmless "what is this row" fields for audit metadata (never the whole row). */
export function safeLabel(row: object): Record<string, unknown> {
	const out: Record<string, unknown> = {};
	for (const key of ['code', 'nameLao', 'name', 'date', 'employeeCode']) {
		const v = (row as Record<string, unknown>)[key];
		if (v !== undefined && v !== null && typeof v !== 'object') out[key] = v;
		else if (v instanceof Date) out[key] = v.toISOString().slice(0, 10);
	}
	return out;
}

export interface AuditUpdatedInput {
	action: AuditActionCode | (string & {});
	entityType: AuditEntityType | (string & {});
	entityId: number | string;
	companyId?: number | null;
	employeeId?: number | null;
	before: object;
	after: object;
	/** the fields the request could change (usually Object.keys(input)) */
	fields: readonly string[];
	metadata?: Record<string, unknown> | null;
}

/** Writes an "updated" event with a normalised before/after diff — or nothing if nothing changed. */
export async function auditUpdated(db: AuditDb, input: AuditUpdatedInput) {
	const changes = buildChanges(
		input.before as Record<string, unknown>,
		input.after as Record<string, unknown>,
		input.fields
	);
	if (!changes) return null;
	return writeAuditEvent(db, {
		action: input.action,
		entityType: input.entityType,
		entityId: input.entityId,
		companyId: input.companyId,
		employeeId: input.employeeId,
		changes,
		metadata: input.metadata
	});
}
