/**
 * THE single writer of audit events. Domain services call `writeAuditEvent(tx, …)` with the SAME
 * transaction client as the state change, so a rollback leaves no "success" event behind. There is
 * no update/delete API for audit rows anywhere in the application.
 */
export type AuditDb = Prisma.TransactionClient | typeof prisma;

